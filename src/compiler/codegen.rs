        self.emit("  ASL".to_string());
        self.emit("  ASL".to_string());
        self.emit("  ASL".to_string());
        self.emit("  ASL".to_string());
        self.emit("  ASL".to_string());
        self.emit("  TAX".to_string());

        self.emit("  LDY #$02".to_string());
        self.emit("  LDA ($F0), Y".to_string());
        self.output
